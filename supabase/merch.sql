-- =============================================================================
-- Battle on Imperial — merchandise pre-orders
--
-- The order form on merch.html. Public key can INSERT and nothing else;
-- organisers work the list in Tournament Control → Merch Orders (New → Paid
-- → Picked up) and see a size tally for ordering stock. Each new order emails
-- the buyer the order number and Zelle details, and alerts the organisers,
-- through the registration-email edge function.
--
-- The total is checked against the published prices here, so a tampered
-- page cannot place a $0 order. EDIT merch_price() when prices change —
-- together with PRODUCTS in assets/merch.js and merch-templates.ts.
--
-- Run in the SQL Editor after admin-schema.sql. Safe to re-run.
-- =============================================================================

create or replace function public.merch_price(item_id text)
returns int
language sql
immutable
as $$
  select case item_id
    when 'tee'     then 15
    when 'hoodie'  then 30
    when 'pants'   then 20
    when 'lanyard' then 7
    when 'pin'     then 5
  end;
$$;

-- Sum of qty × price over the items array; null if any item is unknown, which
-- fails the CHECK below.
create or replace function public.merch_total(items jsonb)
returns int
language sql
immutable
as $$
  select case
    when jsonb_typeof(items) <> 'array' then null
    when exists (select 1 from jsonb_array_elements(items) i where public.merch_price(i->>'id') is null) then null
    else (select coalesce(sum(public.merch_price(i->>'id') * (i->>'qty')::int), 0)::int
          from jsonb_array_elements(items) i)
  end;
$$;

-- Shape check for the items array. A CHECK constraint may not contain a
-- subquery, but it may call a function that does.
create or replace function public.merch_items_ok(items jsonb)
returns boolean
language sql
immutable
as $$
  select jsonb_typeof(items) = 'array'
     and jsonb_array_length(items) between 1 and 30
     and not exists (
       select 1 from jsonb_array_elements(items) i
       where public.merch_price(i->>'id') is null
          or coalesce(i->>'qty', '') !~ '^[0-9]+$'
          or (i->>'qty')::int not between 1 and 10
     );
$$;

create table if not exists public.merch_orders (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),

  -- Generated by the page: BOI- plus five characters.
  order_no    text not null unique check (order_no ~ '^BOI-[A-Z0-9]{5}$'),

  name        text not null check (char_length(name) between 2 and 120),
  school      text check (school is null or char_length(school) <= 120),
  email       text not null check (
                char_length(email) <= 200
                and email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
              ),
  phone       text not null check (char_length(phone) between 7 and 40),

  -- [{ "id": "hoodie", "size": "M", "qty": 2 }, ...]
  items       jsonb not null check (public.merch_items_ok(items)),
  total       int not null check (total > 0 and total = public.merch_total(items)),

  notes       text check (notes is null or char_length(notes) <= 1000),
  ack         boolean not null default false,

  -- Worked by the organisers; the public form can never write these.
  status      text not null default 'new'
              check (status in ('new', 'paid', 'picked_up', 'cancelled')),
  paid_at     timestamptz,
  internal_notes text
);

create index if not exists merch_orders_created_at_idx on public.merch_orders (created_at desc);
create index if not exists merch_orders_status_idx on public.merch_orders (status);

alter table public.merch_orders enable row level security;

drop policy if exists "anon can place a merch order" on public.merch_orders;
create policy "anon can place a merch order"
  on public.merch_orders
  for insert to anon
  with check (status = 'new' and paid_at is null and internal_notes is null);

drop policy if exists "admins read merch orders" on public.merch_orders;
create policy "admins read merch orders" on public.merch_orders
  for select to authenticated using (public.is_admin());

drop policy if exists "admins update merch orders" on public.merch_orders;
create policy "admins update merch orders" on public.merch_orders
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admins delete merch orders" on public.merch_orders;
create policy "admins delete merch orders" on public.merch_orders
  for delete to authenticated using (public.is_admin());

revoke all on public.merch_orders from anon;
grant insert on public.merch_orders to anon;
grant select, update, delete on public.merch_orders to authenticated;

-- -----------------------------------------------------------------------------
-- Email on a new order — same pattern as the other triggers; the webhook
-- secret is read from the registration trigger.
-- -----------------------------------------------------------------------------

create extension if not exists pg_net with schema extensions;

create or replace function public.notify_merch_order_email()
returns trigger
language plpgsql
security definer
set search_path = extensions, public, pg_temp
as $$
declare
  fn_url  text := 'https://gduaigjclvqsraesnvrh.supabase.co/functions/v1/registration-email';
  secret  text;
begin
  select substring(p.prosrc from 'secret\s+text\s*:=\s*''([^'']*)''')
    into secret
  from pg_proc p
  where p.proname = 'notify_registration_email'
    and p.pronamespace = 'public'::regnamespace;

  if secret is null or secret = '' or secret = 'PASTE_WEBHOOK_SECRET_HERE' then
    raise warning 'merch order saved but not emailed: no webhook secret on notify_registration_email()';
    return new;
  end if;

  perform net.http_post(
    url     := fn_url,
    headers := jsonb_build_object(
                 'Content-Type', 'application/json',
                 'x-boi-secret', secret
               ),
    body    := jsonb_build_object(
                 'type',   'INSERT',
                 'table',  'merch_orders',
                 'schema', 'public',
                 'record', to_jsonb(new)
               ),
    timeout_milliseconds := 15000
  );
  return new;
end;
$$;

revoke all on function public.notify_merch_order_email() from public, anon, authenticated;

drop trigger if exists merch_orders_email_notify on public.merch_orders;
create trigger merch_orders_email_notify
  after insert on public.merch_orders
  for each row
  execute function public.notify_merch_order_email();

